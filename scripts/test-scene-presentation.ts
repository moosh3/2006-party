import assert from 'node:assert/strict';
import { scenePosition, spriteSpotlight } from '../lib/scene-presentation';
import { SPRITES } from '../lib/cast';
const clock = { playbackState: 'playing', playbackPositionSeconds: 47, snapshotReceivedAt: 1000 };
assert.equal(scenePosition(clock, 2000), 48);
assert.equal(spriteSpotlight(scenePosition(clock, 2000), 6).person, 2, 'Late arrivals join the current profile');
assert.equal(scenePosition({ ...clock, playbackState: 'paused' }, 90000), 47, 'Pause freezes the presentation');
assert.equal(scenePosition({ ...clock, playbackDurationSeconds: 48 }, 90000), 47.95, 'Scene end cannot run into another cue');
assert.equal(scenePosition({ ...clock, snapshotRoundTripMs: 200 }, 2000), 48.1);
assert.equal(scenePosition({ ...clock, snapshotRoundTripMs: 20000 }, 1000), 48, 'Latency estimate is bounded');
assert.equal(scenePosition({}, 10000), 0);
assert.deepEqual(spriteSpotlight(144, 6), { person: 0, line: 0 }, 'Six-person sequence repeats');
assert.deepEqual(spriteSpotlight(23.99, 6), { person: 0, line: 2 });
assert.deepEqual(spriteSpotlight(24, 6), { person: 1, line: 0 });
assert.deepEqual(spriteSpotlight(8, 6), { person: 0, line: 1 });
assert.deepEqual(spriteSpotlight(0, 6), { person: 0, line: 0 }, 'Restart returns to the first profile');
assert.deepEqual(spriteSpotlight(NaN, 6), { person: 0, line: 0 });
assert.equal(new Set(SPRITES.map((_, i) => spriteSpotlight(i * 24, SPRITES.length).person)).size, 6);
console.log('PASS projector clock: late join, pause, duration, latency, all six profiles, phrases, restart and repeat.');
